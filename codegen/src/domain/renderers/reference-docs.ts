import { isObject, type JsonValue } from "../json-schema.ts";
import { reachableTitles, type OpenApiDocument } from "../openapi-bundle.ts";
import { busEvents, type OpcodeEntry, type Registries } from "../registry.ts";
import type { SchemaBundle } from "../schema-bundle.ts";
import { schemaSection, section, table, typeLabel } from "./markdown.ts";
import type { TitleLookup } from "./ts-events.ts";

export interface ReferenceInput {
  registries: Registries;
  bundle: SchemaBundle;
  titleOf: TitleLookup;
  /** Source path (relative to schemas/) of the file defining a title. */
  sourceOf: (title: string) => string;
  openapi: OpenApiDocument;
}

const HEADER = "<!-- Generated by @discordy-voics/contracts-codegen from the contracts sources. Do not edit; copy into the docs repo. -->";
const code = (text: string | number) => `\`${text}\``;
const page = (title: string, ...parts: string[]) => `${HEADER}\n\n${section(1, title, ...parts)}\n`;

function opcodeTable(opcodes: OpcodeEntry[], titleOf: TitleLookup): string {
  return table(
    ["Op", "Name", "Direction", "Payload", "Description"],
    opcodes.map((o) => [String(o.op), code(o.name), o.direction, o.payload ? code(titleOf(o.payload)) : "—", o.description]),
  );
}

function payloadSections(level: number, titles: string[], bundle: SchemaBundle): string {
  return [...new Set(titles)].map((t) => schemaSection(level, t, bundle)).join("\n\n");
}

/** Types reachable from `roots` that live outside objects/ and are not roots themselves. */
function supportingTypes(roots: string[], input: ReferenceInput): string[] {
  const rootSet = new Set(roots);
  return [...reachableTitles(roots, input.bundle)].filter((t) => !rootSet.has(t) && !input.sourceOf(t).startsWith("objects/")).sort();
}

const payloadTitles = (entries: Array<{ payload: string | null }>, titleOf: TitleLookup) =>
  entries.flatMap((e) => (e.payload ? [titleOf(e.payload)] : []));

function renderGateway(input: ReferenceInput): string {
  const { protocol, intents } = input.registries;
  const g = protocol.gateway;
  const opTitles = payloadTitles(g.opcodes, input.titleOf);
  const dispatchTitles = payloadTitles(g.dispatch_events, input.titleOf).filter((t) => !input.sourceOf(t).startsWith("objects/"));
  const support = supportingTypes([...opTitles, ...dispatchTitles], input);
  return page(
    "Gateway protocol",
    `Clients connect to \`wss://<gateway>${g.path}?v=${g.version}&encoding=${g.encoding}\`. The server sends HELLO with a heartbeat interval of ${g.heartbeat_interval_ms} ms. ` +
      `Sessions can be resumed for ${g.resume_window_s} s (up to ${g.resume_buffer_max} buffered dispatches). ` +
      `Clients may send ${g.rate_limit_sends} frames per ${g.rate_limit_window_s} s; exceeding it closes with 4008. ` +
      "Objects referenced below (User, Channel, ...) are described in rest.md.",
    "Add `&compress=zstd-stream` to receive binary frames containing one continuous zstd stream per WebSocket connection. Each event is flushed for immediate decoding. Client-to-server frames stay JSON text. A reconnect, including RESUME, starts a fresh stream. Without the parameter server frames are JSON text; unknown compression values are rejected.",
    section(2, "Frame", schemaSection(3, "GatewayFrame", input.bundle)),
    section(2, "Opcodes", opcodeTable(g.opcodes, input.titleOf)),
    section(2, "Opcode payloads", payloadSections(3, opTitles, input.bundle)),
    section(2, "Close codes", table(["Code", "Name", "Description", "Reconnect"], g.close_codes.map((c) => [String(c.code), code(c.name), c.description, c.reconnect ? "yes" : "no"]))),
    section(
      2,
      "Intents",
      "Discord bit values. User sessions implicitly receive every intent; privileged intents require approval for bots.",
      table(
        ["Bit", "Value", "Name", "Privileged", "Events"],
        intents.intents.map((i) => [`1 << ${i.bit}`, String(i.value), code(i.name) + (i.discord_name ? ` (Discord: ${code(i.discord_name)})` : ""), i.privileged ? "yes" : "no", i.events.join(", ") || "—"]),
      ),
    ),
    section(
      2,
      "Dispatch events",
      table(
        ["Event (`t`)", "Payload (`d`)", "Source", "Topic", "Description"],
        g.dispatch_events.map((e) => [code(e.name), e.payload ? code(input.titleOf(e.payload)) : "`null`", e.source, e.topic ? code(e.topic) : "—", e.description]),
      ),
    ),
    section(2, "Dispatch payloads", payloadSections(3, dispatchTitles, input.bundle)),
    support.length ? section(2, "Supporting types", payloadSections(3, support, input.bundle)) : "",
  );
}

function renderVoice(input: ReferenceInput): string {
  const v = input.registries.protocol.voice;
  const opTitles = payloadTitles(v.opcodes, input.titleOf);
  const sfuTitles = payloadTitles([...v.sfu_commands, ...v.sfu_events], input.titleOf);
  const support = supportingTypes([...opTitles, ...sfuTitles], input);
  return page(
    "Voice protocol",
    `Clients open \`wss://<node ws_url>${v.path}\` with the token from VOICE_SERVER_UPDATE. The node sends HELLO with a heartbeat interval of ${v.heartbeat_interval_ms} ms. ` +
      "Voice nodes are ICE-lite; the client synthesises the remote SDP from SESSION_DESCRIPTION.",
    section(2, "Frame", schemaSection(3, "VoiceFrame", input.bundle)),
    section(2, "Opcodes", opcodeTable(v.opcodes, input.titleOf)),
    section(2, "Opcode payloads", payloadSections(3, opTitles, input.bundle)),
    section(2, "Speaking flags", table(["Value", "Name"], v.speaking_flags.map((f) => [String(f.value), code(f.name)]))),
    section(
      2,
      "SFU control",
      "Signaling talks to the co-located SFU over TCP `127.0.0.1:4101` with newline-delimited JSON. After an SFU restart, signaling replays `create_session` for every live session.",
      table(["Kind", "Name", "Payload", "Description"], [
        ...v.sfu_commands.map((c) => ["command (`cmd`)", code(c.name), code(input.titleOf(c.payload)), c.description]),
        ...v.sfu_events.map((e) => ["event (`evt`)", code(e.name), code(input.titleOf(e.payload)), e.description]),
      ]),
      payloadSections(3, sfuTitles, input.bundle),
    ),
    section(2, "Node discovery", payloadSections(3, ["VoiceNodeRegistration", "VoiceNodeHealth", "VoiceNodeBlacklist"], input.bundle)),
    section(2, "Voice token claims", payloadSections(3, ["VoiceTokenClaims", "ProbeVoiceTokenClaims"], input.bundle)),
    support.length ? section(2, "Supporting types", payloadSections(3, support, input.bundle)) : "",
  );
}

function renderEvents(input: ReferenceInput): string {
  const { protocol } = input.registries;
  const busOnlyTitles = payloadTitles(protocol.events.bus_only_events, input.titleOf);
  return page(
    "Event bus",
    `Services publish JSON envelopes (version ${protocol.events.envelope_version}) to Redpanda. \`data\` is exactly the gateway DISPATCH payload for \`type\` (see gateway.md).`,
    section(2, "Envelope", schemaSection(3, "EventEnvelope", input.bundle)),
    section(
      2,
      "Routing",
      "- If `guild_id` is set and `target_user_ids` is null, the gateway fans out through the guild process, filtered by VIEW_CHANNEL on `channel_id` and by intents.\n" +
        "- Otherwise the event is delivered to every session of each user in `target_user_ids`.\n" +
        "- Consumers are idempotent on `id` (UUIDv7); the gateway keeps an LRU of the last 10k event IDs per node.\n" +
        `- ${protocol.events.user_topic_events.map(code).join(", ")} is also published on \`discordy.user.v1\` (with \`target_user_ids\`) for DMs.`,
    ),
    section(2, "Topics", table(["Topic", "Key", "Producers"], protocol.events.topics.map((t) => [code(t.name), t.key, t.producers.join(", ")]))),
    section(2, "Event types", table(["Type", "Topic", "Payload (`data`)"], busEvents(protocol).map((e) => [code(e.name), code(e.topic), e.payload ? code(input.titleOf(e.payload)) : "`null`"]))),
    section(2, "Bus-only payloads", payloadSections(3, busOnlyTitles, input.bundle)),
  );
}

function bodyLabel(content: JsonValue | undefined): string {
  if (!isObject(content)) return "—";
  const json = content["application/json"];
  if (!isObject(json)) return "—";
  return code(typeLabel(isObject(json.schema) ? rewriteComponentRefs(json.schema) : undefined));
}

function rewriteComponentRefs(schema: Record<string, JsonValue>): JsonValue {
  return JSON.parse(JSON.stringify(schema).replace(/#\/components\/schemas\//g, "#/$defs/")) as JsonValue;
}

function renderRest(input: ReferenceInput): string {
  const { protocol } = input.registries;
  const doc = input.openapi;
  const byTag = new Map<string, string[][]>();
  for (const [path, item] of Object.entries(isObject(doc.paths) ? doc.paths : {})) {
    if (!isObject(item)) continue;
    for (const [method, op] of Object.entries(item)) {
      if (!isObject(op)) continue;
      const tag = Array.isArray(op.tags) ? String(op.tags[0]) : "Other";
      const responses = isObject(op.responses) ? op.responses : {};
      const success = Object.entries(responses).find(([status]) => status.startsWith("2"));
      const response = success && isObject(success[1]) ? (success[1].content === undefined ? `${success[0]} No Content` : bodyLabel(success[1].content)) : "—";
      const request = isObject(op.requestBody) ? bodyLabel(op.requestBody.content) : "—";
      const rows = byTag.get(tag) ?? [];
      rows.push([code(method.toUpperCase()), code(path), String(op["x-discordy-service"] ?? "api"), request, response, String(op.summary ?? "")]);
      byTag.set(tag, rows);
    }
  }
  const endpointSections = [...byTag.entries()].map(([tag, rows]) => section(3, tag, table(["Method", "Path", "Service", "Request", "Response", "Summary"], rows)));
  const titlesIn = (prefix: string) => Object.keys(input.bundle.$defs).filter((t) => input.sourceOf(t).startsWith(prefix)).sort();
  return page(
    "REST API",
    `Base path \`${protocol.rest.base_path}\`. JSON, snake_case, Discord API v10 object shapes plus Discordy extras. IDs are Snowflakes and permission sets are 64-bit integers, both serialized as decimal strings. ` +
      "Authenticate with `Authorization: Bearer <access token>` or `Authorization: Bot <token>`. The machine-readable description is `openapi/discordy.yaml`.",
    section(2, "Rate limits", `Responses carry ${protocol.rest.rate_limit_headers.map(code).join(", ")}. A 429 response also carries \`Retry-After\`.`),
    section(2, "Errors", "Errors use the envelope `{ \"code\": int, \"message\": string, \"errors\"?: object }`.", table(["Code", "Name", "HTTP", "Description"], protocol.rest.error_codes.map((e) => [String(e.code), code(e.name), String(e.http_status), e.description]))),
    section(
      2,
      "Delivery modes",
      table(["Mode", "Strictness"], protocol.delivery_modes.map((m) => [code(m.name), String(m.strictness)])),
      "- Guild channels: the channel's `delivery_mode`, set by members with MANAGE_CHANNELS.\n" +
        "- DMs and group DMs: the strictest of each participant's per-chat override, falling back to their `default_delivery_mode`.\n" +
        `- \`ephemeral\` is rejected (400) for guild channels viewable by more than ${protocol.delivery_mode_limits.ephemeral_max_guild_viewers} members; \`p2p\` for guild channels and group DMs with more than ${protocol.delivery_mode_limits.p2p_max_group_dm_members} members.\n` +
        "- `POST /channels/{id}/messages` returns 409 with code 50160 when the effective mode is not `standard`.",
    ),
    section(2, "Endpoints", ...endpointSections),
    section(2, "Objects", payloadSections(3, titlesIn("objects/"), input.bundle)),
    section(2, "Request and response bodies", payloadSections(3, titlesIn("rest/"), input.bundle)),
  );
}

export function renderReferenceDocs(input: ReferenceInput): Record<string, string> {
  return {
    "gateway.md": renderGateway(input),
    "voice.md": renderVoice(input),
    "events.md": renderEvents(input),
    "rest.md": renderRest(input),
  };
}
