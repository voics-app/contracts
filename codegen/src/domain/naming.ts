/** Case conversions between registry names (SCREAMING_SNAKE / PascalCase) and target languages. */

export const GENERATED_NOTICE = "Code generated by @discordy-voics/contracts-codegen from the contracts sources. DO NOT EDIT.";

export function screamingToPascal(name: string): string {
  return name
    .toLowerCase()
    .split("_")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

export function pascalToSnake(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1_$2")
    .toLowerCase();
}

export function screamingToSnake(name: string): string {
  return name.toLowerCase();
}
